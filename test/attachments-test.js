const test=require('node:test');
const assert=require('node:assert/strict');
const http=require('node:http');
const {seed}=require('../src/quiz/seed');
const {createQuizApi}=require('../src/quiz/api');
const {toTables,fromTables}=require('../src/db/schema');
const markdown='# Saved teaching report\nPackets carry data. Latency measures delay and bandwidth describes capacity. Professor-reviewed material is preserved.';
async function settled(job) { while(['queued','running'].includes(job.status)) await new Promise(r=>setTimeout(r,5)); }
test('attachment removal, reattachment and report confirmation preserve history without inference',async t=>{
  const db=seed(),course=db.courses.find(c=>c.id==='c-comp'),topic=db.topics.find(t=>t.courseId===course.id);
  let calls=0, blocked=false;
  const api=createQuizApi({store:{db,save(){},flush:async()=>{},pending:()=>blocked},authoringAI:async()=>{calls++;return {json:{markdown,insufficient:false}};}});
  const server=http.createServer((req,res)=>api.handle(req,res));
  await new Promise(r=>server.listen(0,'127.0.0.1',r));t.after(()=>new Promise(r=>server.close(r)));
  const base=`http://127.0.0.1:${server.address().port}`,path='/api/teacher/courses/c-comp';
  async function req(method,url,body,token){const r=await fetch(base+url,{method,headers:{'content-type':'application/json',...(token?{authorization:'Bearer '+token}:{})},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,body:await r.json()};}
  const teacher=(await req('POST','/api/login',{userId:'t-a'})).body.token;
  const student=(await req('POST','/api/login',{userId:'s-01'})).body.token;
  const upload={topicId:topic.id,outcomeId:topic.outcomes[0].id,confirmNoPersonalData:true,origin:'pdf',documentId:'a'.repeat(64),fileName:'old.pdf',title:'old.pdf · Page 1',text:'Attached original lecture. '+markdown};
  const a=(await req('POST',path+'/import',upload,teacher)).body;
  const b=(await req('POST',path+'/import',{...upload,documentId:'b'.repeat(64),fileName:'keep.pptx',title:'keep.pptx · Slide 1',origin:'pptx'},teacher)).body;
  const ids=()=>db.passages.filter(p=>p.courseId===course.id && p.importHash && p.attached!==false).map(p=>p.id);
  const start=await req('POST',path+'/authoring',{kind:'report',materialIds:ids()},teacher);
  const original=course.authoringJobs.find(j=>j.id===start.body.id);await settled(original);
  assert.equal(original.status,'complete');
  for(const [revision,text] of [[0,markdown],[1,markdown+'\nA saved professor clarification.']])
    assert.equal((await req('PUT',path+`/authoring/${original.id}/review`,{reportRevision:revision,markdown:text},teacher)).status,200);
  const history=JSON.stringify(db.passages.filter(p=>p.origin==='report')),questions=JSON.stringify(db.questions),oldJob=JSON.stringify(original);
  const before=calls,body={passageIds:[a.id],attached:false};
  assert.equal((await req('PUT',path+'/imports',body)).status,401);
  assert.equal((await req('PUT',path+'/imports',body,student)).status,403);
  assert.equal((await req('PUT','/api/teacher/courses/c-stats/imports',body,teacher)).status,404);
  assert.equal((await req('PUT',path+'/imports',{passageIds:[original.reportSourceId],attached:false},teacher)).status,404);
  assert.equal((await req('PUT',path+'/imports',body,teacher)).status,200);
  assert.equal((await req('PUT',path+'/imports',body,teacher)).status,200,'lost response retry is idempotent');
  assert.equal(db.passages.find(p=>p.id===a.id).attached,false);
  assert.equal(fromTables(toTables(db,()=>1)).passages.find(p=>p.id===a.id).attached,false);
  assert.equal(JSON.stringify(db.passages.filter(p=>p.origin==='report')),history);
  assert.equal(JSON.stringify(db.questions),questions);
  assert.equal(JSON.stringify(original),oldJob);
  assert.equal(calls,before);
  assert.equal((await req('POST',path+'/authoring',{kind:'report',materialIds:ids()},teacher)).status,409,'changed attachments require confirmation');
  assert.equal((await req('POST',path+'/authoring',{kind:'report',confirmMaterialChange:true,materialIds:[a.id,b.id]},teacher)).status,409,'stale confirmation cannot use removed files');
  assert.equal(calls,before);
  const next=await req('POST',path+'/authoring',{kind:'report',confirmMaterialChange:true,materialIds:ids()},teacher);
  assert.equal(next.status,202);
  const job=course.authoringJobs.find(j=>j.id===next.body.id);await settled(job);
  assert.ok(!job.input.passageIds.includes(a.id));assert.ok(job.input.passageIds.includes(b.id));
  assert.deepEqual(job.input.passageIds,[b.id],'only currently attached uploaded excerpts are analysed');
  assert.equal(course.authoringJobs.length,2);assert.equal(JSON.stringify(original),oldJob);
  const after=calls;
  const restored=await req('POST',path+'/import',upload,teacher);
  assert.equal(restored.body.id,a.id);assert.equal(restored.body.attached,true);
  assert.equal(db.passages.filter(p=>p.importHash===a.importHash).length,1);
  assert.equal(calls,after,'file management and reattachment never infer');
  job.status='running';
  assert.equal((await req('PUT',path+'/imports',body,teacher)).status,409,'protect authorized in-flight work');
  assert.equal((await req('POST',path+'/import',upload,teacher)).status,409);
  job.status='complete';blocked=true;
  assert.equal((await req('PUT',path+'/imports',body,teacher)).status,503,'do not acknowledge undurable changes');
});
